function glyphs(text) {
  return [...text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase()]
    .map((ch) => (ch === '\u2026' ? '...' : ch))
    .join('')
    .split('')
    .map((ch) => G[ch])
    .filter(Boolean);
}

export function textWidth(text) {
  const gs = glyphs(text);
  return gs.reduce((w, g) => w + g[0].length, 0) + Math.max(0, gs.length - 1);
}

export function drawText(p, text, x, y, color, alpha = 1) {
  let cx = x;
  for (const g of glyphs(text)) {
    p.bitmap(g, cx, y, color, alpha);
    cx += g[0].length + 1;
  }
}

// Shortens text with ".." until it fits in `max` font pixels.
export function fit(text, max) {
  if (textWidth(text) <= max) return text;
  let t = text;
  while (t.length > 1 && textWidth(`${t}..`) > max) t = t.slice(0, -1);
  return `${t.trimEnd()}..`;
}
